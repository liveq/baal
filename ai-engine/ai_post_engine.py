def react_to_existing():
    """최근 글 위주로 AI가 추가 반응 — 시간 지난 글에는 거의 안 달림"""
    pool = []
    # 1. 최근 6시간 이내 글 (메인 타겟)
    recent = supabase_query("posts", "select=id,title,content,board_type,comment_count,upvotes&is_deleted=eq.false&order=created_at.desc&limit=15")
    if recent:
        pool.extend(recent)
    # 2. 댓글 0개인 글 (아무도 안 봐주면 안 되니까)
    no_comments = supabase_query("posts", "select=id,title,content,board_type,comment_count,upvotes&comment_count=eq.0&is_deleted=eq.false&order=created_at.desc&limit=3")
    if no_comments:
        pool.extend(no_comments)

    if not pool:
        return

    # 중복 제거
    seen = set()
    unique = []
    for p in pool:
        if p["id"] not in seen:
            seen.add(p["id"])
            unique.append(p)

    # 추천 높은 글에 가중치
    # 댓글 0개 글에 높은 가중치 — 뉴스에도 댓글 달리도록
    weights = [10 if p.get("comment_count", 0) == 0 else max(1, p.get("upvotes", 0) // 5 + 1) for p in unique]
    post = random.choices(unique, weights=weights, k=1)[0]
    board = post.get("board_type", "free")
    agents = list(AGENTS.keys())

    # 게시판에 적합한 에이전트 선택
    suitable = [a for a in agents if board in AGENT_BOARDS.get(a, {})]
    if not suitable:
        suitable = agents

    agent = random.choice(suitable)
    comment = generate_comment(0, agent, post["title"], post.get("content", "")[:500], board)

    if comment and comment.get("content"):
        # community comments에 직접 저장
        supabase_insert("comments", {
            "post_id": post["id"],
            "content": comment["content"],
            "author_nickname": PERSONAS_NAMES.get(agent, agent),
            "upvotes": 0,
            "downvotes": 0,
            "is_deleted": False,
        })
        # comment_count 업데이트
        existing = supabase_query("comments", f"select=id&post_id=eq.{post['id']}")
        cnt = len(existing) if existing else 0
        requests.patch(
            f"{SUPABASE_URL}/rest/v1/posts?id=eq.{post['id']}",
            json={"comment_count": cnt},
            headers={"apikey": SUPABASE_KEY, "Authorization": f"Bearer {SUPABASE_KEY}", "Content-Type": "application/json"},
            timeout=10,
        )
        name = PERSONAS_NAMES.get(agent, agent)
        print(f"  [REACT] {name} → {post['title'][:30]}")


