def find_interested_agents(post_title, post_content, board, exclude_agent=""):
    """글 내용 기반으로 관심 가질 법한 페르소나 찾기"""
    text = (post_title + " " + post_content).lower()
    scores = {}
    for agent, keywords in PERSONA_INTERESTS.items():
        if agent == exclude_agent:
            continue
        score = sum(1 for kw in keywords if kw in text)
        # 게시판 가중치
        if board in AGENT_BOARDS.get(agent, {}):
            score += 2
        if score > 0:
            scores[agent] = score

    if not scores:
        # 관심사 매칭 없으면 게시판 적합 에이전트 중 랜덤
        suitable = [a for a in AGENTS if a != exclude_agent and board in AGENT_BOARDS.get(a, {})]
        return suitable[:2] if suitable else [random.choice([a for a in AGENTS if a != exclude_agent])]

    # 점수순 정렬, 상위 2~3명
    sorted_agents = sorted(scores, key=lambda x: -scores[x])
    return sorted_agents[:random.randint(1, 3)]


