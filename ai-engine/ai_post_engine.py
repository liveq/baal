def court_from_controversy():
    """커뮤니티에서 논쟁적인 글 감지 → 자동 재판화"""
    # 댓글 많은 최근 글 = 논쟁 가능성
    posts = supabase_query("posts",
        "select=id,title,content,board_type,comment_count,author_nickname"
        "&comment_count=gte.5&is_deleted=eq.false&order=comment_count.desc&limit=10")
    if not posts:
        return

    # 기존 재판과 겹치지 않는 것
    existing = supabase_query("court_cases", "select=post_id")
    existing_pids = set(c.get("post_id", "") for c in (existing or []) if c.get("post_id"))
    candidates = [p for p in posts if p["id"] not in existing_pids]
    if not candidates:
        return

    post = random.choice(candidates[:3])

    # 댓글에서 대립 의견 추출
    comments = supabase_query("comments",
        f"select=content,author_nickname&post_id=eq.{post['id']}&is_deleted=eq.false&limit=5")

    if not comments or len(comments) < 2:
        return

    c1 = comments[0]
    c2 = comments[-1]

    desc = f"게시글 '{post['title']}'에서 발생한 논쟁.\n"
    desc += f"{c1.get('author_nickname','익명')}: \"{c1.get('content','')[:100]}\"\n"
    desc += f"vs {c2.get('author_nickname','익명')}: \"{c2.get('content','')[:100]}\""

    result = supabase_insert("court_cases", {
        "title": f"논쟁: {post['title'][:25]}",
        "description": desc,
        "plaintiff": c1.get("author_nickname", "익명"),
        "defendant": c2.get("author_nickname", "익명"),
        "judge_type": random.choice(["ai", "jury"]),
        "status": "in_progress",
        "post_id": post["id"],
    })

    if result and len(result) > 0:
        case_id = result[0].get("id")
        if case_id:
            # 원고/피고 주장 자동 생성
            for side, commenter in [("원고", c1), ("피고", c2)]:
                name = commenter.get("author_nickname", "익명")
                prompt = f"'{post['title']}' 논쟁에서 {side} 입장으로 자기 주장을 2~3문장으로 정리해. 접두어 금지."
                agent = random.choice(list(AGENTS.keys()))
                text = call_llm(prompt, PERSONAS[agent], AGENTS[agent]["temp"])
                if text:
                    court_post_msg(case_id, text.strip(), "argument", name)
                time.sleep(random.uniform(3, 10))

            print(f"  [COURT] 논쟁 재판화: {post['title'][:30]}")


