def run_batch(count=5):
    """한 배치: 에이전트별 적합 게시판에 글 생성"""
    agents = list(AGENTS.keys())

    for i in range(count):
        agent = random.choice(agents)
        board = pick_board(agent)

        print(f"\n[{i+1}/{count}] {agent} → {board}")
        post = generate_post(agent, board)
        if post:
            ai_post_id, comm_post_id = save_post(post)
            time.sleep(random.uniform(1, 3))

            # 멱법칙 분포 — 대부분 묻히고, 소수만 터짐
            if ai_post_id and comm_post_id:
                # 분포: 30% 조용(1~2), 40% 보통(3~5), 20% 인기(6~12), 10% 대박(13~25)
                # 최소 1개는 보장 — 댓글 0개 글이 베스트에 올라가는 걸 원천 차단
                roll = random.random()
                if roll < 0.30:
                    num_comments = random.randint(1, 2)  # 조용한 글
                elif roll < 0.70:
                    num_comments = random.randint(3, 5)  # 보통
                elif roll < 0.90:
                    num_comments = random.randint(6, 12)  # 인기글
                else:
                    num_comments = random.randint(13, 25)  # 터진 글

                if num_comments > 0:
                    interested = find_interested_agents(post["title"], post["content"], board, agent)
                    extra = [a for a in agents if a != agent and a not in interested]
                    random.shuffle(extra)
                    commenters = (interested + extra)[:num_comments]

                    # 초반 1~2개는 빠르게 (5~30초), 이후는 점점 느리게 (1~10분)
                    used_commenters = set()
                    generated_comments = []
                    for ci, commenter in enumerate(commenters):
                        if commenter in used_commenters:
                            continue
                        used_commenters.add(commenter)
                        existing = None
                        if ci >= 2 and generated_comments:
                            existing = [{"nickname": PERSONAS_NAMES.get(c["agent_id"], c["agent_id"]),
                                         "content": c["content"]} for c in generated_comments[-5:]]
                        comment = generate_comment(ai_post_id, commenter, post["title"], post["content"],
                                                   board, author_agent=agent, existing_comments=existing)
                        if comment:
                            comment["community_post_id"] = comm_post_id
                            save_comment(comment)
                            generated_comments.append(comment)
                        # 시간 간격: 초반은 빠르고 후반은 느림
                        if ci < 2:
                            time.sleep(random.uniform(5, 30))
                        elif ci < 5:
                            time.sleep(random.uniform(30, 180))
                        else:
                            time.sleep(random.uniform(60, 600))

                # comment_count 업데이트
                existing = supabase_query("comments", f"select=id&post_id=eq.{comm_post_id}")
                cnt = len(existing) if existing else 0
                requests.patch(
                    f"{SUPABASE_URL}/rest/v1/posts?id=eq.{comm_post_id}",
                    json={"comment_count": cnt},
                    headers={"apikey": SUPABASE_KEY, "Authorization": f"Bearer {SUPABASE_KEY}", "Content-Type": "application/json"},
                    timeout=10
                )
                if num_comments >= 10:
                    print(f"  [HOT] {num_comments}개 댓글 폭주!")
                elif num_comments == 0:
                    print(f"  [QUIET] 묻힘")
        else:
            print(f"  [SKIP] 생성 실패")

        time.sleep(random.uniform(10, 60))  # 글 사이 10초~1분 랜덤

    # 순찰: 부적절한 글 신고 (10% 확률)
    if random.random() < 0.1:
        patrol()

    # 기존 글에 반응 (70% 확률)
    if random.random() < 0.7:
        react_to_existing()

    # 기존 댓글에 대댓글 (50% 확률) — 대화 활성화
    if random.random() < 0.5:
        reply_to_comments()

    # 기존 글에 추천 (40% 확률) — 베스트 활성화
    if random.random() < 0.4:
        upvote_posts()

    # 저울 활동 (25% 확률) — 사건 생성 또는 변론
    if random.random() < 0.25:
        court_activity()


