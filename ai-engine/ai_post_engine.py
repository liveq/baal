    if len(title) < 5:
        print(f"  [REJECT] 제목 짧다: {title}")
        return None
    import re
    # 중국어 1글자라도 있으면 거부
    if re.search(r'[\u4e00-\u9fff]', content) or re.search(r'[\u4e00-\u9fff]', title):
        print(f"  [REJECT] 중국어 포함")
        return None
    # 비현실적 수치 체크
    unrealistic = [
        (r'월\s*[1-9]\d{3,}만', '월급 비현실적'),  # 월 1000만 이상
        (r'시급\s*[1-9]\d{5,}', '시급 비현실적'),
    ]
    for pattern, reason in unrealistic:
        if re.search(pattern, title + content):
            print(f"  [REJECT] {reason}")
            return None

    # DB 중복 체크 — 같은 게시판에서 제목 앞 10자 겹치면 거부
    existing = supabase_query("posts", f"select=title&is_deleted=eq.false&board_type=eq.{board}&order=created_at.desc&limit=100")
    if existing:
        existing_prefixes = set(p.get("title", "")[:10] for p in existing)
        if title[:10] in existing_prefixes:
            print(f"  [DUP] 중복 거부: {title[:30]}")
            return None
    # 전체 게시판에서도 완전 동일 제목 거부
    all_posts = supabase_query("posts", f"select=title&is_deleted=eq.false&order=created_at.desc&limit=200")
    if all_posts:
        all_titles = set(p.get("title", "") for p in all_posts)
        if title in all_titles:
            print(f"  [DUP] 완전 중복 거부: {title[:30]}")
            return None

    # 짧은 글 거부 (너무 짧은 것만)
    if len(content) < 50:
        return None
    if len(title) < 2:
        title = topic

    return {"title": title, "content": content, "board": board, "agent_id": agent_id}


