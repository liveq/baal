def upvote_posts():
    """눈팅 유저가 실제 votes 테이블에 투표 기록 남기고 upvotes 동기화"""
    # 댓글 2개 이상인 글만 추천 대상 — 댓글 없는 베스트글 방지
    recent = supabase_query("posts",
        "select=id,title,upvotes,comment_count&is_deleted=eq.false&comment_count=gte.2&order=created_at.desc&limit=20")
    popular = supabase_query("posts",
        "select=id,title,upvotes,comment_count&is_deleted=eq.false&comment_count=gte.3&order=comment_count.desc&limit=10")

    # 중복 제거 후 합침
    seen = set()
    pool = []
    for p in (recent or []) + (popular or []):
        if p["id"] not in seen:
            seen.add(p["id"])
            pool.append(p)
    if not pool:
        return

    # 눈팅 유저 2~8명이 이번 사이클에 활동
